const fs=require("fs"),vm=require("vm"),assert=require("assert/strict");
const data=new Map();
const localStorage={getItem:k=>data.get(k)??null,setItem:(k,v)=>data.set(k,String(v)),removeItem:k=>data.delete(k)};
const ctx=vm.createContext({localStorage,console,setTimeout:f=>f(),URLSearchParams,window:{location:{pathname:"/tester.html",replace(){}},addEventListener(){}}});
const api=fs.readFileSync("js/api.js","utf8");
const seed=fs.readFileSync("js/datos-tester.js","utf8");
vm.runInContext(api+"\n"+seed+"\nthis.app={cargarDatosTester,dbListaPromise};",ctx);
(async()=>{
 await ctx.app.dbListaPromise;
 const original=JSON.parse(data.get("cicsa_usuarios"));
 await ctx.app.cargarDatosTester();
 const usuarios=JSON.parse(data.get("cicsa_usuarios"));
 assert.equal(usuarios.length,original.length+8);
 original.forEach(u=>assert.deepEqual(usuarios.find(x=>x.id===u.id),u));
 const snapshot=JSON.stringify([...data]);
 await ctx.app.cargarDatosTester();
 assert.equal(JSON.stringify([...data]),snapshot);
 const fresh=vm.createContext({localStorage,console,setTimeout:f=>f(),URLSearchParams,window:{location:{pathname:"/index.html",replace(){}},addEventListener(){}}});
 vm.runInContext(api+"\nthis.app={auth,sesion,cursos,progreso,reportes,soporte,dbListaPromise};",fresh);
 const a=fresh.app;await a.dbListaPromise;
 const login=async name=>{const r=await a.auth.login(name,"Tester2026");a.sesion.guardar(r.token,r.usuario);};
 await login("tester.nuevo");
 assert.ok((await a.cursos.listar()).some(c=>c.nombre.startsWith("[TEST]")&&c.estado==="publicado"));
 assert.equal((await a.soporte.listar()).length,1);
 await assert.rejects(a.auth.login("tester.inactivo","Tester2026"));
 await login("tester.instructor");
 assert.equal((await a.cursos.listar()).length,4);
 await login("tester.superadmin");
 assert.ok((await a.reportes.seguimiento()).some(r=>r.usuario==="Trabajador aprobado TEST"&&r.nota===100));
 const bancos=JSON.parse(data.get("cicsa_evaluaciones"));
 Object.values(bancos).forEach(b=>{if(b.examen) b.examen.preguntas.forEach(p=>assert.ok(p.enunciado));});
 console.log("PASS: datos preservados, carga sin duplicados, persistencia, roles, soporte y resultados.");
})().catch(e=>{console.error(e);process.exitCode=1});
