const fs=require("fs"),vm=require("vm"),assert=require("assert/strict");
const data=new Map();
const localStorage={getItem:k=>data.get(k)??null,setItem:(k,v)=>data.set(k,String(v)),removeItem:k=>data.delete(k),key:i=>[...data.keys()][i],get length(){return data.size}};
const ctx=vm.createContext({localStorage,console,setTimeout:fn=>{fn();return 0},URLSearchParams,window:{location:{pathname:"/index.html",replace(){}},addEventListener(){}}});
vm.runInContext(fs.readFileSync("js/api.js","utf8")+"\nthis.app={sesion,auth,usuarios,cursos,notificacionesAdmin,DB,dbListaPromise};",ctx);
(async()=>{
 const a=ctx.app; await a.dbListaPromise;
 const login=async(name,pw)=>{const r=await a.auth.login(name,pw);a.sesion.guardar(r.token,r.usuario);return r.usuario;};
 const instructor=await login("instructor","Instructor2026");
 const curso=await a.cursos.crear({nombre:"Curso para revisar",horas:2,descripcion:"Curso enviado por instructor"});
 assert.equal(curso.estado,"pendiente");
 assert.ok(a.DB.notificacionesAdmin.some(n=>n.tipo==="curso-revision"&&n.cursoId===curso.id&&n.destinatarioRol==="superadmin"));
 await login("administrador","AdminDemo2026");
 assert.ok((await a.notificacionesAdmin.listar()).some(n=>n.tipo==="curso-revision"),"Admin normal también recibe aviso de curso nuevo pendiente");
 await assert.rejects(a.cursos.cambiarEstado(curso.id,"publicado"),/permisos|Súper administrador/i);
 await login("ana","Admin2026");
 let avisos=await a.notificacionesAdmin.listar();
 assert.ok(avisos.some(n=>n.tipo==="curso-revision"&&n.cursoId===curso.id),"Súper admin recibe la alerta");
 await a.cursos.cambiarEstado(curso.id,"publicado","Aprobado. Buen contenido.");
 let revisado=await a.cursos.obtener(curso.id);
 assert.equal(revisado.estado,"publicado");
 assert.equal(revisado.solicitudCurso.comentario,"Aprobado. Buen contenido.");
 assert.equal((await a.notificacionesAdmin.listar()).some(n=>n.cursoId===curso.id&&n.tipo==="curso-revision"),false,"La alerta se retira al resolver");
 await login("instructor","Instructor2026");
 await a.cursos.actualizar(curso.id,{descripcion:"Versión actualizada"});
 revisado=await a.cursos.obtener(curso.id);
 assert.equal(revisado.estado,"pendiente");
 assert.equal(revisado.solicitudCurso.comentario,"");
 await login("ana","Admin2026");
 assert.ok((await a.notificacionesAdmin.listar()).some(n=>n.cursoId===curso.id&&n.tipo==="curso-revision"));
 await assert.rejects(a.cursos.cambiarEstado(curso.id,"rechazado",""),/comentario/);
 await a.cursos.cambiarEstado(curso.id,"rechazado","Corrige el segundo módulo y vuelve a enviarlo.");
 revisado=await a.cursos.obtener(curso.id);
 assert.equal(revisado.estado,"rechazado");
 assert.equal(revisado.solicitudCurso.resultado,"cambios");
 assert.equal(revisado.solicitudCurso.comentario,"Corrige el segundo módulo y vuelve a enviarlo.");
 await login("instructor","Instructor2026");
 revisado=await a.cursos.obtener(curso.id);
 assert.equal(revisado.solicitudCurso.comentario,"Corrige el segundo módulo y vuelve a enviarlo.");
 const avisosInstructor=await a.notificacionesAdmin.listar();
 assert.ok(avisosInstructor.some(n=>n.tipo==="curso-rechazado"&&n.cursoId===curso.id&&n.comentario==="Corrige el segundo módulo y vuelve a enviarlo."),"Instructor recibe rechazo con el comentario del revisor.");
 console.log("PASS: instructor notification -> superadmin approval/comment -> instructor status/comment flow.");
})().catch(e=>{console.error(e);process.exitCode=1});
